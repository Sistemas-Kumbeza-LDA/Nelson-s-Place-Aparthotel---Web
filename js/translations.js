// Current language - Default to Portuguese on first visit
let currentLang = localStorage.getItem('nelsonsplace_lang') || 'pt';

// Function to translate the page
function translatePage(lang) {
    currentLang = lang;
    localStorage.setItem('nelsonsplace_lang', lang);
    
    // Update HTML lang attribute
    document.documentElement.lang = lang;
    
    // Update active button
    document.querySelectorAll('.lang-btn').forEach(btn => {
        btn.classList.remove('active');
        if (btn.dataset.lang === lang) {
            btn.classList.add('active');
        }
    });
    
    // Translate all elements with data-translate attribute
    document.querySelectorAll('[data-translate]').forEach(element => {
        const key = element.dataset.translate;
        if (translations[lang] && translations[lang][key]) {
            // For input elements, translate the value attribute
            if (element.tagName === 'INPUT' && element.type === 'submit') {
                element.value = translations[lang][key];
            } else {
                element.textContent = translations[lang][key];
            }
        }
    });
    
    // Translate input values with data-translate-value attribute
    document.querySelectorAll('[data-translate-value]').forEach(element => {
        const key = element.dataset.translateValue;
        if (translations[lang] && translations[lang][key]) {
            element.value = translations[lang][key];
        }
    });
    
    // Translate placeholders
    document.querySelectorAll('[data-translate-placeholder]').forEach(element => {
        const key = element.dataset.translatePlaceholder;
        if (translations[lang] && translations[lang][key]) {
            element.placeholder = translations[lang][key];
        }
    });
    
    // Update data-hover attribute for fx-slide buttons
    document.querySelectorAll('a.fx-slide[data-translate-hover]').forEach(element => {
        const key = element.dataset.translateHover;
        if (translations[lang] && translations[lang][key]) {
            element.setAttribute('data-hover', translations[lang][key]);
        }
    });
}

// Initialize translation system
document.addEventListener('DOMContentLoaded', function() {
    // Set initial language
    translatePage(currentLang);
    
    // Add click handlers to language buttons
    document.querySelectorAll('.lang-btn').forEach(btn => {
        btn.addEventListener('click', function() {
            translatePage(this.dataset.lang);
        });
    });
});
